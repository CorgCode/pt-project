"""Regenerate demo/synthetic_run: a small, clearly SYNTHETIC result bundle for the dashboard and docs.

    python -m experiments.make_demo_bundle --output demo/synthetic_run

Runs the fixture end to end (fixed seed), then copies the report, figures, results, identity,
leaderboards, audit, manifest, scored embeddings and the frozen test neighbours, with absolute paths
removed. Everything is stamped `synthetic: true`; it is NOT LANL data and not a benchmark result.
"""
from __future__ import annotations

import argparse
import json
import shutil
import tempfile
from pathlib import Path

from experiments.end_to_end import end_to_end

BANNER = """# Synthetic demo bundle - NOT LANL data

Generated by `python -m experiments.make_demo_bundle` from a synthetic fixture written in the LANL
netflow layout (`pipeline/fixtures.py`, seed 0, 300 hosts). It exists so the dashboard and the docs
can show a complete run; every file inside is stamped `synthetic: true`. The numbers say nothing
about real network behaviour and must not be quoted as benchmark results.
"""


def _clean(obj, prefix: str):
    if isinstance(obj, dict):
        return {k: _clean(v, prefix) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_clean(v, prefix) for v in obj]
    if isinstance(obj, str) and prefix in obj:
        return obj.replace(prefix, "<workdir>")
    return obj


def build(output: Path, *, n_hosts: int = 300, seed: int = 0, n_boot: int = 200) -> Path:
    output = Path(output)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp).resolve()
        end_to_end(work, fixture=True, n_hosts=n_hosts, seed=seed, n_boot=n_boot, pairs_per_anchor=10)
        if output.exists():
            shutil.rmtree(output)
        run, ref = output / "run", output / "reference"
        shutil.copytree(work / "run", run)
        for t in ("validation", "test"):
            (ref / t).mkdir(parents=True)
            shutil.copy(work / "reference" / t / "manifest.json", ref / t / "manifest.json")
        shutil.copy(work / "reference" / "test" / "neighbors.csv", ref / "test" / "neighbors.csv")
        shutil.copy(work / "processed" / "manifest.json", output / "processed_manifest.json")
        for sub in ("embeddings",):                       # keep only the scored (train-window) embeddings
            pass
        for path in output.rglob("*.json"):
            data = json.loads(path.read_text(encoding="utf-8"))
            path.write_text(json.dumps(_clean(data, str(work)), indent=2, sort_keys=True) + "\n", encoding="utf-8")
        for path in output.rglob("*.md"):
            path.write_text(path.read_text(encoding="utf-8").replace(str(work), "<workdir>"), encoding="utf-8")
        (output / "README.md").write_text(BANNER, encoding="utf-8")
    return output


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", type=Path, default=Path("demo/synthetic_run"))
    ap.add_argument("--n-hosts", type=int, default=300)
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    print(build(a.output, n_hosts=a.n_hosts, seed=a.seed))


if __name__ == "__main__":
    main()
